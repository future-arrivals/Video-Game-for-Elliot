// Copies Design/slice-data.json into an ES module the game imports.
// The design JSON stays the single source of truth; re-run `npm run gen` after editing it.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../Design/slice-data.json');
const out = join(here, '../src/data/slice.gen.js');
const data = JSON.parse(readFileSync(src, 'utf8'));
writeFileSync(out, '// GENERATED by tools/gen-data.mjs from Design/slice-data.json. Do not edit.\nexport default ' + JSON.stringify(data, null, 1) + ';\n');
console.log('wrote', out);
